def build(type_id, family, crop, image_size):
    f=FAMILIES[family];x,y,r,b=f['bounds'];sx=f['width']/(r-x);sy=f['depth']/(b-y)
    # Image coordinates point down; the application's plan coordinates point up.
    def point(p): return [round((p[0]-x)*sx,4),round((b-p[1])*sy,4)]
    plan={'schemaVersion':1,'isDemo':False,'scaleStatus':'proportional',
          'coordinateSystem':{'unit':'m','pivot':[f['width']/2,f['depth']/2]},
          'dimensionEvidence':{'note':'공개 기본형 원본의 방·벽·개구부를 수동 대조한 비례 재구성. 치수·벽 두께·층고·문창 높이는 실측 전 개략값이며 실제 세대 방향·확장 상태는 별도 확인.'},
          'outline':list(map(point,f['outline'])),
          'rooms':[{'id':f'room-{i}','name':name,'polygon':list(map(point,poly)),'label':point(label)} for i,(name,poly,label) in enumerate(f['rooms'])],
          'walls':[],'doors':[],'windows':[]}
    for i,a in enumerate(f['outline']):
        z=f['outline'][(i+1)%len(f['outline'])]
        plan['walls'].append({'id':f'outer-{i}','start':point(a),'end':point(z),'thickness':.12,'height':2.4})
        segment,offset,width,route=ENTRIES[family]
        if a+z==segment:
            scale=sx if a[0]!=z[0] else sy
            plan['doors'].append({'id':'main-door','wallId':f'outer-{i}','offset':round(offset*scale,4),'width':round(width*scale,4),'height':2.05,'sillHeight':0,'hinge':'start','opensTo':'left'})
            plan['entry']={'doorId':'main-door','roomId':next(r['id'] for r in plan['rooms'] if r['name']=='현관'),'route':list(map(point,route)),'note':'현관에서 거실로 이동하는 타입 기준 동선'}
    for i,w in enumerate(f['walls']):
        a,c=point(w[:2]),point(w[2:4]);wid=f'partition-{i}'
        plan['walls'].append({'id':wid,'start':a,'end':c,'thickness':.10,'height':2.4})
        scale=sx if w[0]!=w[2] else sy
        for kind,slots in [('doors',w[4] if len(w)>4 else []),('windows',w[5] if len(w)>5 else [])]:
            for offset,width in slots:
                v={'id':f'{kind}-{i}-{offset}','wallId':wid,'offset':round(offset*scale,4),'width':round(width*scale,4),'height':2.0 if kind=='doors' else 1.9,'sillHeight':0 if kind=='doors' else .1}
                if kind=='doors':v.update(hinge='start',opensTo='left')
                plan[kind].append(v)
    source=next(t for s in SOURCES for t in s['types'] if t['id']==type_id)
    image=ROOT/f'output/research/models/{type_id}.jpg'
    return {'typeId':type_id,'variant':'base','sourceImage':source['basicImage'],
            'sha256':hashlib.sha256(image.read_bytes()).hexdigest(),
            'crop':{'x':crop[0]/image_size[0],'y':crop[1]/image_size[1],'width':(crop[2]-crop[0])/image_size[0],'height':(crop[3]-crop[1])/image_size[1]},'plan':plan}


